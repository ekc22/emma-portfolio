/**
 * Generates the Supabase migrations and seed from lib/schema.ts and lib/data/seed.ts,
 * so the database, the app's validation and the AI tools share one definition.
 *
 *   npm run db:generate
 *
 * Writes:
 *   supabase/migrations/20261112000001_schema.sql   tables, constraints, indexes, triggers
 *   supabase/migrations/20261112000002_rls.sql      row-level security by role
 *   supabase/seed.sql                               fictional demo data (dates relative to load time)
 */
import fs from "node:fs";
import path from "node:path";
import { ENTITIES, TABLES, type FieldDef, type TableName } from "../lib/schema";
import { buildSeed, DEMO_PERSONAS, ORG_ID, personId } from "../lib/data/seed";

const root = path.join(path.dirname(new URL(import.meta.url).pathname), "..");
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

/** Columns not described in the registry (system, provenance and workflow fields). */
const EXTRA: Partial<Record<TableName, string[]>> = {
  reports: ["sources jsonb not null default '[]'::jsonb", "data jsonb", "approved_by text", "approved_at timestamptz", "edited_by text"],
  ai_recommendations: [
    "target_id uuid", "action text not null default 'create' check (action in ('create','update'))", "payload jsonb not null default '{}'::jsonb",
    "source_refs jsonb not null default '[]'::jsonb", "decided_by text", "decided_at timestamptz", "applied_record_id uuid", "rejection_reason text",
    "meeting_id uuid references public.meetings(id) on delete set null", "meeting_action_id uuid references public.meeting_actions(id) on delete set null",
  ],
  audit_logs: ["actor_id uuid", "action text not null", "record_id uuid", "changes jsonb"],
};

/** Columns in the registry that the database fills or that need a non-default type. */
const SKIP: Partial<Record<TableName, string[]>> = { audit_logs: ["created_at"] };

function colType(table: TableName, f: FieldDef): string {
  const nn = f.required ? " not null" : "";
  switch (f.type) {
    case "number":
    case "currency":
      return `numeric${nn}`;
    case "percent":
      return `numeric${nn} check (${f.key} between 0 and 100)`;
    case "score":
      return `smallint${nn} check (${f.key} between 1 and 5)`;
    case "date":
      return `date${nn}`;
    case "datetime":
      return `timestamptz${nn}`;
    case "boolean":
      return "boolean not null default false";
    case "select":
      return `text${nn}` + (f.options ? ` check (${f.key} in (${f.options.map(q).join(", ")}))` : "");
    case "relation": {
      const target = f.relation!;
      const onDelete = f.required && target !== "users" ? "cascade" : "set null";
      return `uuid${nn} references public.${target}(id) on delete ${onDelete}`;
    }
    default:
      return `text${nn}`;
  }
}

// Order tables so foreign keys point backwards.
function ordered(): TableName[] {
  const out: TableName[] = [];
  const visit = (t: TableName, stack: Set<TableName>) => {
    if (out.includes(t) || stack.has(t)) return;
    stack.add(t);
    for (const f of ENTITIES[t].fields) if (f.type === "relation" && f.relation && f.relation !== t) visit(f.relation, stack);
    if (t === "ai_recommendations") { visit("meetings", stack); visit("meeting_actions", stack); }
    stack.delete(t);
    out.push(t);
  };
  visit("organisations", new Set());
  for (const t of TABLES) visit(t, new Set());
  return out;
}

function schemaSql() {
  const lines: string[] = [
    "-- CoS OS schema. Generated by scripts/generate-sql.ts from lib/schema.ts. Do not edit by hand.",
    "create extension if not exists pgcrypto;",
    "",
    "create or replace function public.touch_updated_at() returns trigger language plpgsql as $$",
    "begin new.updated_at = now(); return new; end $$;",
    "",
  ];
  const cycles: string[] = [];
  for (const t of ordered()) {
    const def = ENTITIES[t];
    const cols = [
      "id uuid primary key default gen_random_uuid()",
      t === "organisations" ? "organisation_id uuid not null check (organisation_id = id)" : "organisation_id uuid not null references public.organisations(id) on delete cascade",
      "created_at timestamptz not null default now()",
      "updated_at timestamptz not null default now()",
      "created_by uuid",
    ];
    for (const f of def.fields) {
      if (SKIP[t]?.includes(f.key)) continue;
      // Self-references and forward references are added after all tables exist.
      if (f.type === "relation" && f.relation && ordered().indexOf(f.relation) >= ordered().indexOf(t)) {
        cols.push(`${f.key} uuid`);
        cycles.push(`alter table public.${t} add constraint ${t}_${f.key}_fkey foreign key (${f.key}) references public.${f.relation}(id) on delete set null deferrable initially immediate;`);
        continue;
      }
      cols.push(`${f.key} ${colType(t, f)}`);
    }
    for (const x of EXTRA[t] ?? []) cols.push(x);
    lines.push(`create table if not exists public.${t} (\n  ${cols.join(",\n  ")}\n);`);
    lines.push(`create index if not exists ${t}_org_idx on public.${t} (organisation_id);`);
    for (const f of def.fields) if (f.type === "relation") lines.push(`create index if not exists ${t}_${f.key}_idx on public.${t} (${f.key});`);
    lines.push(`create trigger ${t}_touch before update on public.${t} for each row execute function public.touch_updated_at();`, "");
  }
  lines.push(...cycles, "");
  lines.push(
    "-- Who belongs to which organisation, and with which role.",
    "create table if not exists public.memberships (",
    "  id uuid primary key default gen_random_uuid(),",
    "  auth_user_id uuid not null references auth.users(id) on delete cascade,",
    "  person_id uuid references public.users(id) on delete set null,",
    "  organisation_id uuid not null references public.organisations(id) on delete cascade,",
    "  role text not null check (role in ('owner','admin','executive','member','viewer')),",
    "  created_at timestamptz not null default now(),",
    "  unique (auth_user_id, organisation_id)",
    ");",
    "create index if not exists memberships_user_idx on public.memberships (auth_user_id);",
    "",
  );
  return lines.join("\n");
}

function rlsSql() {
  const lines = [
    "-- CoS OS row-level security. Generated by scripts/generate-sql.ts. Mirrors lib/auth/permissions.ts.",
    "",
    "create or replace function public.org_role(org uuid) returns text",
    "language sql stable security definer set search_path = public as $$",
    "  select role from public.memberships where organisation_id = org and auth_user_id = auth.uid() limit 1",
    "$$;",
    "",
    "create or replace function public.can_read(org uuid, grp text) returns boolean",
    "language sql stable security definer set search_path = public as $$",
    "  select case grp",
    "    when 'core' then public.org_role(org) is not null",
    "    when 'investor' then public.org_role(org) in ('owner','admin','executive')",
    "    when 'financial' then public.org_role(org) in ('owner','admin','executive')",
    "    when 'admin' then public.org_role(org) in ('owner','admin')",
    "    else false end",
    "$$;",
    "",
    "create or replace function public.can_write(org uuid, grp text) returns boolean",
    "language sql stable security definer set search_path = public as $$",
    "  select case grp",
    "    when 'core' then public.org_role(org) in ('owner','admin','executive','member')",
    "    when 'investor' then public.org_role(org) in ('owner','admin','executive')",
    "    when 'financial' then public.org_role(org) in ('owner','admin')",
    "    when 'admin' then public.org_role(org) in ('owner','admin')",
    "    else false end",
    "$$;",
    "",
  ];
  for (const t of TABLES) {
    const g = ENTITIES[t].group;
    lines.push(`alter table public.${t} enable row level security;`);
    if (t === "audit_logs") {
      lines.push(
        `create policy audit_read on public.audit_logs for select using (public.can_read(organisation_id, 'admin'));`,
        `create policy audit_insert on public.audit_logs for insert with check (public.org_role(organisation_id) is not null and actor_id = auth.uid());`,
        "-- No update or delete policies: the audit log is append-only.",
        "",
      );
      continue;
    }
    if (t === "ai_usage") {
      lines.push(
        `create policy ai_usage_read on public.ai_usage for select using (actor_id = auth.uid()::text or public.can_read(organisation_id, 'admin'));`,
        `create policy ai_usage_insert on public.ai_usage for insert with check (public.org_role(organisation_id) is not null and actor_id = auth.uid()::text);`,
        `create policy ai_usage_update on public.ai_usage for update using (actor_id = auth.uid()::text) with check (actor_id = auth.uid()::text);`,
        "",
      );
      continue;
    }
    if (t === "organisations") {
      lines.push(
        `create policy org_read on public.organisations for select using (public.can_read(id, 'core'));`,
        `create policy org_update on public.organisations for update using (public.can_write(id, 'admin')) with check (public.can_write(id, 'admin'));`,
        "",
      );
      continue;
    }
    // Members (any role that writes core records) may file AI proposals; deciding is checked again on apply.
    lines.push(
      `create policy ${t}_read on public.${t} for select using (public.can_read(organisation_id, '${g}'));`,
      `create policy ${t}_insert on public.${t} for insert with check (public.can_write(organisation_id, '${g}'));`,
      `create policy ${t}_update on public.${t} for update using (public.can_write(organisation_id, '${g}')) with check (public.can_write(organisation_id, '${g}'));`,
      `create policy ${t}_delete on public.${t} for delete using (public.can_write(organisation_id, '${g}'));`,
      "",
    );
  }
  lines.push(
    "alter table public.memberships enable row level security;",
    "create policy memberships_read on public.memberships for select using (auth_user_id = auth.uid() or public.can_read(organisation_id, 'admin'));",
    "create policy memberships_write on public.memberships for all using (public.can_write(organisation_id, 'admin')) with check (public.can_write(organisation_id, 'admin'));",
    "",
    "-- Owner protection: only an owner can create, change or remove an owner membership,",
    "-- or grant the owner role. Admins manage everyone else. The service role (auth.uid() is null)",
    "-- is exempt so first-owner setup works; app code checks roles before using it.",
    "create or replace function public.protect_owner_memberships() returns trigger",
    "language plpgsql security definer set search_path = public as $$",
    "declare caller_role text;",
    "begin",
    "  if auth.uid() is null then return coalesce(new, old); end if;",
    "  caller_role := public.org_role(coalesce(new.organisation_id, old.organisation_id));",
    "  if caller_role is distinct from 'owner' and (",
    "       (tg_op in ('UPDATE','DELETE') and old.role = 'owner')",
    "    or (tg_op in ('INSERT','UPDATE') and new.role = 'owner')",
    "  ) then",
    "    raise exception 'Only an owner can grant, change or remove owner access' using errcode = '42501';",
    "  end if;",
    "  if tg_op = 'UPDATE' and (new.auth_user_id is distinct from old.auth_user_id or new.organisation_id is distinct from old.organisation_id) then",
    "    raise exception 'A membership cannot be moved to another login or workspace' using errcode = '42501';",
    "  end if;",
    "  return coalesce(new, old);",
    "end $$;",
    "create trigger memberships_protect_owner before insert or update or delete on public.memberships",
    "  for each row execute function public.protect_owner_memberships();",
    "",
    "grant usage on schema public to authenticated;",
    "grant select, insert, update, delete on all tables in schema public to authenticated;",
    "revoke all on all tables in schema public from anon;",
    "",
  );
  return lines.join("\n");
}

function lit(v: unknown, col: string): string {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (typeof v === "object") return `${q(JSON.stringify(v))}::jsonb`;
  const s = String(v);
  const d = s.match(/^@@D:(-?\d+)@@$/);
  if (d) return `(current_date + ${Number(d[1])})`;
  const t = s.match(/^@@T:(-?\d+):(\d\d:\d\d)@@$/);
  if (t) return `((current_date + ${Number(t[1])}) + time '${t[2]}')::timestamptz`;
  void col;
  return q(s);
}

function seedSql() {
  const data = buildSeed();
  const lines = [
    "-- CoS OS demo data: Fernhill Systems Ltd, a fictional company. Generated by scripts/generate-sql.ts.",
    "-- Dates are relative to the day the seed is loaded.",
    `-- Organisation id: ${ORG_ID}`,
    ...DEMO_PERSONAS.map((p) => `-- Demo persona ${p.personKey} (${p.role}): person id ${personId(p.personKey)}`),
    "",
    "begin;",
    "set constraints all deferred;",
  ];
  for (const t of ordered()) {
    const rows = data[t] ?? [];
    if (!rows.length) continue;
    const cols = Object.keys(rows[0]);
    lines.push(`insert into public.${t} (${cols.join(", ")}) values`);
    lines.push(rows.map((r) => `  (${cols.map((c) => lit(r[c], c)).join(", ")})`).join(",\n") + ";");
  }
  lines.push("commit;", "");
  return lines.join("\n");
}

fs.mkdirSync(path.join(root, "supabase/migrations"), { recursive: true });
fs.writeFileSync(path.join(root, "supabase/migrations/20261112000001_schema.sql"), schemaSql());
fs.writeFileSync(path.join(root, "supabase/migrations/20261112000002_rls.sql"), rlsSql());
fs.writeFileSync(path.join(root, "supabase/seed.sql"), seedSql());
console.log("Wrote supabase/migrations/*.sql and supabase/seed.sql");
